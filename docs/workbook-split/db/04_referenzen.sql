-- ---------------------------------------------------------------------------
-- Vorjahr 2025: Kontensalden mit denselben Regeln klassifizieren wie die
-- laufenden Buchungen, damit der Vergleich methodisch sauber ist.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE VIEW controlling.v_guv_vorjahr AS
SELECT r.jahr,
       r.konto,
       COALESCE(c.name, r.text)               AS text,
       r.wert,
       c.kategorie,
       c.import_art,
       controlling.f_db_stufe(r.konto::int)   AS db_stufe,
       controlling.f_klr_typ(r.konto::int)    AS klr_typ,
       controlling.f_klr_gruppe(r.konto::int) AS klr_gruppe,
       controlling.f_guv_gruppe(r.konto::int) AS guv_gruppe,
       controlling.f_sortierung(r.konto::int) AS guv_sort,
       CASE WHEN controlling.f_db_stufe(r.konto::int) = 0 THEN -r.wert ELSE 0 END AS leistung,
       CASE WHEN controlling.f_db_stufe(r.konto::int) = 1 THEN  r.wert ELSE 0 END AS k_var,
       CASE WHEN controlling.f_db_stufe(r.konto::int) = 2 THEN  r.wert ELSE 0 END AS k_fix,
       CASE WHEN controlling.f_db_stufe(r.konto::int) = 9 THEN  r.wert ELSE 0 END AS neutral
FROM controlling.guv_konten_referenz r
LEFT JOIN controlling.kontenkatalog_tvf c ON c.konto = r.konto
WHERE r.konto ~ '^[0-9]+$'
  -- Bestandskonten gehoeren nicht in die Ergebnisrechnung. Welche das sind,
  -- weiss nur der Kontenkatalog; aus der Kontonummer ist es nicht ableitbar.
  AND COALESCE(c.kategorie, '') NOT LIKE 'bilanz%';

COMMIT;
