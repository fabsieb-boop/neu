-- ============================================================================
--  Referenzwerte fuer den Abgleich
--
--  Zwei unabhaengige Quellen aus dem TVF-Bestandssystem, gegen die sich die
--  aus den Buchungen gerechneten Zahlen pruefen lassen:
--
--   1. BCS-GuV 2026 (data/guv-2026.js, Stand 30.07.2026, Ist bis Periode 6)
--      Kennzahlen des gesamten Buchungskreises je Szenario sowie Segment-
--      ergebnisse je Region.
--   2. SAP-Jahres-GuV 2025 (data/gesamt-guv-2025.js, Stand 31.12.2025)
--      245 Kontensalden des Vorjahres, gleiche Vorzeichenlogik wie der
--      Einzelpostenexport: Kosten positiv, Erloese negativ.
--
--  Diese Tabellen werden nur gelesen. Sie ersetzen keine Buchung, sondern
--  dienen dem Nachweis, wie weit die auftragsbezogene Rechnung von der
--  Gesamt-GuV abweicht und warum.
--
--  Idempotent, beliebig oft ausfuehrbar.
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS controlling.guv_referenz (
  jahr      SMALLINT NOT NULL,
  szenario  VARCHAR(10) NOT NULL,   -- ist | fc | jahr | vorjahr
  position  VARCHAR(40) NOT NULL,
  betrag    NUMERIC(18,2) NOT NULL,
  PRIMARY KEY (jahr, szenario, position)
);

COMMENT ON TABLE controlling.guv_referenz IS
  'BCS-GuV der TVF ALTWERT GmbH. Praesentationslogik: Ertraege positiv, Kostenbloecke als positive Betraege.';

CREATE TABLE IF NOT EXISTS controlling.guv_referenz_segment (
  jahr    SMALLINT NOT NULL,
  segment VARCHAR(60) NOT NULL,
  ist     NUMERIC(18,2),
  fc      NUMERIC(18,2),
  jahr_gesamt NUMERIC(18,2),
  PRIMARY KEY (jahr, segment)
);

CREATE TABLE IF NOT EXISTS controlling.guv_konten_referenz (
  jahr   SMALLINT NOT NULL,
  konto  VARCHAR(20) NOT NULL,
  text   VARCHAR(255),
  wert   NUMERIC(18,2) NOT NULL,    -- SAP-Vorzeichen: Kosten positiv, Erloese negativ
  PRIMARY KEY (jahr, konto)
);

